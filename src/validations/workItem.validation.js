const Joi = require('joi');
const { objectId } = require('./custom.validation');
const { normalizePhoneToE164 } = require('../utils/phoneNumber');

const contactPhone = Joi.string()
  .trim()
  .allow('')
  .custom((value, helpers) => {
    if (!value) return '';
    const normalized = normalizePhoneToE164(value, { allowEmpty: false });
    return normalized || helpers.error('string.pattern.base');
  })
  .messages({
    'string.pattern.base':
      '"phone" must be a valid local or international phone number',
  });

const assignee = Joi.object({
  kind: Joi.string()
    .valid('user', 'contact', 'all', 'role', 'form_submissions')
    .default('user'),
  userId: Joi.when('kind', {
    is: 'user',
    then: Joi.string().required(),
    otherwise: Joi.any().strip(),
  }),
  roleId: Joi.when('kind', {
    is: 'role',
    then: Joi.string().custom(objectId).required(),
    otherwise: Joi.any().strip(),
  }),
  projectId: Joi.when('kind', {
    is: 'form_submissions',
    then: Joi.string().trim().required(),
    otherwise: Joi.any().strip(),
  }),
  formId: Joi.when('kind', {
    is: 'form_submissions',
    then: Joi.string().trim().allow('', null),
    otherwise: Joi.any().strip(),
  }),
  name: Joi.when('kind', {
    is: 'contact',
    then: Joi.string().trim().max(120).required(),
    otherwise: Joi.string().trim().max(120).default('@all'),
  }),
  email: Joi.when('kind', {
    is: 'contact',
    then: Joi.string().trim().email().allow(''),
    otherwise: Joi.any().strip(),
  }),
  phone: Joi.when('kind', {
    is: 'contact',
    then: contactPhone,
    otherwise: Joi.any().strip(),
  }),
}).custom((value, helpers) => {
  if (value.kind === 'contact' && !value.email && !value.phone) {
    return helpers.message(
      '"email" or "phone" is required for a notification contact'
    );
  }
  return value;
});

const fields = {
  type: Joi.string().valid('event', 'task'),
  title: Joi.string().trim().max(200),
  description: Joi.string().allow('').max(5000),
  startAt: Joi.date(),
  endAt: Joi.date(),
  allDay: Joi.boolean(),
  status: Joi.string().valid(
    'scheduled',
    'in-progress',
    'completed',
    'cancelled'
  ),
  priority: Joi.string().valid('low', 'medium', 'high'),
  assignees: Joi.array().items(assignee),
  formAttachment: Joi.object({
    enabled: Joi.boolean().default(false),
    projectId: Joi.string().trim().allow('', null),
    formId: Joi.string().trim().allow('', null),
    title: Joi.string().trim().max(200).allow('', null),
    publicRef: Joi.string().trim().allow('', null),
    shareRef: Joi.string().trim().allow('', null),
    url: Joi.string().trim().max(1000).allow('', null),
    includeBarcode: Joi.boolean().default(true),
  }).allow(null),
  meeting: Joi.object({
    enabled: Joi.boolean().default(false),
    provider: Joi.string()
      .valid('google_meet', 'jitsi', 'custom')
      .default('jitsi'),
    joinUrl: Joi.string().trim().max(1000).allow('', null),
    meetingId: Joi.string().trim().max(100).allow('', null),
    passcode: Joi.string().trim().max(100).allow('', null),
    autoGenerated: Joi.boolean().default(false),
  }).allow(null),
  resources: Joi.array().items(
    Joi.object({
      title: Joi.string().trim().max(200).required(),
      url: Joi.string().trim().max(2000).required(),
      type: Joi.string()
        .valid('storage', 'url', 'form', 'meeting', 'doc', 'kanban', 'design')
        .default('url'),
      storageFileId: Joi.string().trim().allow('', null),
      description: Joi.string().trim().max(500).allow('', null),
    })
  ),
  aiAgenda: Joi.object({
    summary: Joi.string().trim().allow('', null),
    topics: Joi.array().items(Joi.string().trim().max(300)).max(20),
    objectives: Joi.array().items(Joi.string().trim().max(300)).max(20),
    preparationNotes: Joi.alternatives().try(
      Joi.string().trim().allow('', null),
      Joi.array().items(Joi.string().trim().max(300))
    ),
    nextSteps: Joi.array().items(Joi.string().trim().max(300)).max(20),
    formattedMarkdown: Joi.string().trim().allow('', null),
    generatedAt: Joi.date(),
  }).allow(null),
  idempotencyKey: Joi.string().trim().max(128).allow('', null),
  reminder: Joi.object({
    scheduledAt: Joi.date(),
    minutesBefore: Joi.number().integer().min(1).max(10080),
    timezone: Joi.string().trim().max(64).default('UTC'),
    recurrence: Joi.object({
      frequency: Joi.string().valid('none', 'yearly').default('none'),
    }).default({ frequency: 'none' }),
    channels: Joi.array()
      .items(Joi.string().valid('email', 'whatsapp'))
      .min(1)
      .default(['email']),
  }).or('scheduledAt', 'minutesBefore'),
};

const notificationContact = Joi.object({
  name: Joi.string().trim().max(120).required(),
  email: Joi.string().trim().email().allow(''),
  phone: contactPhone,
}).or('email', 'phone');

const importWorkItem = Joi.object({
  type: fields.type.required(),
  title: fields.title.required(),
  description: fields.description.default(''),
  startAt: fields.startAt.required(),
  endAt: fields.endAt.required(),
  allDay: fields.allDay.default(false),
  status: fields.status.default('scheduled'),
  priority: Joi.when('type', {
    is: 'task',
    then: fields.priority.default('medium'),
    otherwise: Joi.any().strip(),
  }),
  assigneeEmails: Joi.array().items(Joi.string().trim().email()).max(25),
  notificationContacts: Joi.array().items(notificationContact).max(25),
  // Form attachment fields
  formAttachment: fields.formAttachment,
  projectFormId: Joi.string().trim().allow('', null),
  attachForm: Joi.boolean(),
  includeBarcode: Joi.boolean(),
  // Video conference fields
  meeting: fields.meeting,
  enableVideoConference: Joi.boolean(),
  meetingProvider: Joi.string().valid('google_meet', 'jitsi', 'custom'),
  meetingUrl: Joi.string().trim().allow('', null),
  // AI Agenda & outcomes fields
  aiAgenda: fields.aiAgenda,
  agendaTopics: Joi.alternatives().try(
    Joi.array().items(Joi.string().trim().max(300)),
    Joi.string().trim().max(2000)
  ),
  targetedOutcomes: Joi.alternatives().try(
    Joi.array().items(Joi.string().trim().max(300)),
    Joi.string().trim().max(2000)
  ),
  agendaSummary: Joi.string().trim().max(1000).allow('', null),
  // Reminder fields
  reminder: fields.reminder,
  reminderMinutes: Joi.number().integer().min(1).max(10080),
  idempotencyKey: fields.idempotencyKey,
}).custom((value, helpers) => {
  if (value.endAt <= value.startAt) {
    return helpers.message('"endAt" must be after "startAt"');
  }
  return value;
});

module.exports = {
  createWorkItem: {
    body: Joi.object({
      ...fields,
      type: fields.type.required(),
      title: fields.title.required(),
      startAt: fields.startAt.required(),
      endAt: fields.endAt.required(),
    }).custom((value, helpers) => {
      if (value.endAt <= value.startAt) {
        return helpers.message('"endAt" must be after "startAt"');
      }
      return value;
    }),
  },
  queryWorkItems: {
    query: Joi.object({
      from: Joi.date(),
      to: Joi.date(),
      type: fields.type,
      status: fields.status,
    }),
  },
  getWorkItem: {
    params: Joi.object({
      workItemId: Joi.string().custom(objectId).required(),
    }),
  },
  getPublicWorkItem: {
    params: Joi.object({
      workItemId: Joi.string().trim().min(3).max(64).required(),
    }),
  },
  updateWorkItem: {
    params: Joi.object({
      workItemId: Joi.string().custom(objectId).required(),
    }),
    body: Joi.object(fields).min(1),
  },
  importWorkItems: {
    body: Joi.object({
      items: Joi.array().items(importWorkItem).min(1).max(250).required(),
    }),
  },
  generateMeeting: {
    body: Joi.object({
      provider: Joi.string()
        .valid('google_meet', 'jitsi', 'custom')
        .required(),
      title: Joi.string().trim().max(200).allow('', null),
    }),
  },
  addResource: {
    params: Joi.object({
      workItemId: Joi.string().trim().min(3).max(64).required(),
    }),
    body: Joi.object({
      title: Joi.string().trim().max(200).required(),
      url: Joi.string().trim().max(2000).required(),
      type: Joi.string()
        .valid('storage', 'url', 'form', 'meeting', 'doc', 'kanban', 'design')
        .default('url'),
      storageFileId: Joi.string().trim().allow('', null),
      description: Joi.string().trim().max(500).allow('', null),
    }),
  },
};
