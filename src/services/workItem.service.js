const getPublicWorkItem = async (reference) => {
  const isMongoId = mongoose.Types.ObjectId.isValid(reference);
  const query = isMongoId
    ? { $or: [{ _id: reference }, { shareCode: reference }] }
    : { shareCode: reference };

  const item = await WorkItem.findOne(query);
  if (!item) {
    throw new ApiError(httpStatus.NOT_FOUND, 'Event or task not found');
  }

  // Ensure legacy records have a shareCode assigned
  if (!item.shareCode) {
    let code = WorkItem.generateShareCode();
    while (await WorkItem.exists({ shareCode: code })) {
      code = WorkItem.generateShareCode();
    }
    item.shareCode = code;
    await WorkItem.updateOne({ _id: item._id }, { $set: { shareCode: code } }).catch(() => null);
  }

  let aiAgenda = item.aiAgenda
    ? item.aiAgenda.toObject
      ? item.aiAgenda.toObject()
      : { ...item.aiAgenda }
    : null;

  if (!aiAgenda || !aiAgenda.summary) {
    aiAgenda = generateAiAgenda({
      title: item.title,
      description: item.description,
      type: item.type,
      startAt: item.startAt,
      endAt: item.endAt,
      meeting: item.meeting,
      formAttachment: item.formAttachment,
    });
  }

  // Defensively ensure preparationNotes, topics, objectives are arrays
  if (aiAgenda) {
    if (typeof aiAgenda.preparationNotes === 'string') {
      aiAgenda.preparationNotes = [aiAgenda.preparationNotes];
    } else if (!Array.isArray(aiAgenda.preparationNotes)) {
      aiAgenda.preparationNotes = [];
    }
    if (typeof aiAgenda.topics === 'string') {
      aiAgenda.topics = [aiAgenda.topics];
    } else if (!Array.isArray(aiAgenda.topics)) {
      aiAgenda.topics = [];
    }
    if (typeof aiAgenda.objectives === 'string') {
      aiAgenda.objectives = [aiAgenda.objectives];
    } else if (!Array.isArray(aiAgenda.objectives)) {
      aiAgenda.objectives = [];
    }
    if (typeof aiAgenda.nextSteps === 'string') {
      aiAgenda.nextSteps = [aiAgenda.nextSteps];
    } else if (!Array.isArray(aiAgenda.nextSteps)) {
      aiAgenda.nextSteps = [];
    }

    // Provide default structured agenda topics only if none exist
    if (aiAgenda.topics.length === 0) {
      aiAgenda.topics = [
        'Context, Background & Project Alignment',
        'Operational Milestones & Metrics Review',
        'Key Architecture Decisions & Technical Specs',
        'Blockers, Constraints & Resource Allocation',
        'Deliverables, Action Checkpoints & Deadlines',
      ];
    }
  }

  // Resolve Tenant / Organization branding & contact details
  let tenant = {
    name: 'Saby Workspace',
    email: '',
    phone: '',
    address: '',
    city: '',
    state: '',
    country: '',
    website: '',
    logoUrl: '',
  };

  if (item.tenantId) {
    const [onboarding, globalSettings] = await Promise.all([
      TenantOnboarding.findOne({ tenantId: item.tenantId }).lean().catch(() => null),
      GlobalSettings.findOne({ tenantId: item.tenantId }).lean().catch(() => null),
    ]);

    if (onboarding?.company) {
      if (onboarding.company.name) tenant.name = onboarding.company.name;
      if (onboarding.company.email) tenant.email = onboarding.company.email;
      if (onboarding.company.phone) tenant.phone = onboarding.company.phone;

      // Construct a clean, human-friendly address
      const addrComponents = [];
      if (onboarding.company.address && onboarding.company.address.trim().length > 2) {
        addrComponents.push(onboarding.company.address.trim());
      }
      if (onboarding.company.city) addrComponents.push(onboarding.company.city.trim());
      if (onboarding.company.state) addrComponents.push(onboarding.company.state.trim());
      if (onboarding.company.country) addrComponents.push(onboarding.company.country.trim());

      if (addrComponents.length > 0) {
        tenant.address = addrComponents.join(', ');
      }
    }

    if (globalSettings) {
      if (
        (!tenant.name || tenant.name === 'Saby Workspace' || tenant.name === 'Default Organization Name') &&
        globalSettings.organizationName &&
        globalSettings.organizationName !== 'Default Organization Name'
      ) {
        tenant.name = globalSettings.organizationName;
      }
      if (!tenant.email && globalSettings.contactEmail) tenant.email = globalSettings.contactEmail;
      if (!tenant.phone && globalSettings.contactPhone) tenant.phone = globalSettings.contactPhone;
      if (globalSettings.websiteUrl) tenant.website = globalSettings.websiteUrl;
      if (globalSettings.logoUrl) tenant.logoUrl = globalSettings.logoUrl;
    }
  }

  // Fallback to organizer user if email is still missing
  if (!tenant.email && item.createdBy) {
    const organizer = await User.findById(item.createdBy).select('firstname lastname email phoneNumber').lean().catch(() => null);
    if (organizer) {
      if (!tenant.email && organizer.email) tenant.email = organizer.email;
      if (!tenant.phone && organizer.phoneNumber) tenant.phone = organizer.phoneNumber;
      if (!tenant.name || tenant.name === 'Saby Workspace') {
        const orgName = `${organizer.firstname || ''} ${organizer.lastname || ''}`.trim();
        if (orgName) tenant.name = orgName;
      }
    }
  }

  // Resolve resources
  const resources = [];
  if (Array.isArray(item.resources) && item.resources.length > 0) {
    resources.push(
      ...item.resources.map((r) => ({
        id: String(r._id || ''),
        title: r.title,
        url: r.url,
        type: r.type || 'url',
        storageFileId: r.storageFileId || null,
        description: r.description || '',
      }))
    );
  }

  // If form attachment is enabled and not already present
  if (item.formAttachment?.enabled && item.formAttachment?.url) {
    const hasForm = resources.some(
      (r) => r.type === 'form' || r.url === item.formAttachment.url
    );
    if (!hasForm) {
      resources.push({
        id: 'resource-form',
        title: item.formAttachment.title || 'Data Capture Form',
        url: item.formAttachment.url,
        type: 'form',
        description: 'Online submission form',
      });
    }
  }

  // If meeting is enabled and not already present
  if (item.meeting?.enabled && item.meeting?.joinUrl) {
    const hasMeeting = resources.some(
      (r) => r.type === 'meeting' || r.url === item.meeting.joinUrl
    );
    if (!hasMeeting) {
      resources.push({
        id: 'resource-meeting',
        title:
          item.meeting.provider === 'google_meet'
            ? 'Google Meet Room'
            : 'Video Conference',
        url: item.meeting.joinUrl,
        type: 'meeting',
        description: 'Live interactive room',
      });
    }
  }

  // Default suggested resources if none configured yet
  if (resources.length === 0) {
    resources.push(
      {
        id: 'default-kanban',
        title: 'Kanban Board',
        url: '#kanban',
        type: 'kanban',
        description: 'Sprint & operational tasks',
      },
      {
        id: 'default-doc',
        title: 'Documentation',
        url: '#docs',
        type: 'doc',
        description: 'Project brief & guidelines',
      },
      {
        id: 'default-design',
        title: 'Design File',
        url: '#design',
        type: 'design',
        description: 'Figma specs & design tokens',
      }
    );
  }

  return {
    id: String(item._id),
    tenantId: item.tenantId || null,
    createdBy: item.createdBy || null,
    shareCode: item.shareCode || null,
    shortUrl: item.shareCode ? `/a/${item.shareCode}` : `/agenda/${item._id}`,
    title: item.title,
    type: item.type,
    description: item.description,
    startAt: item.startAt,
    endAt: item.endAt,
    allDay: item.allDay,
    status: item.status,
    priority: item.priority,
    assignees: item.assignees || [],
    resources,
    tenant,
    meeting: item.meeting?.enabled ? item.meeting : null,
    formAttachment: item.formAttachment?.enabled ? item.formAttachment : null,
    aiAgenda,
    createdAt: item.createdAt,
  };
};

const addPublicResource = async (reference, resourceBody) => {
  const isId = mongoose.Types.ObjectId.isValid(reference);
  const filter = isId
    ? { $or: [{ _id: reference }, { shareCode: reference }] }
    : { shareCode: reference };

  const item = await WorkItem.findOne(filter);
  if (!item) {
    throw new ApiError(httpStatus.NOT_FOUND, 'Agenda item not found');
  }

  if (!Array.isArray(item.resources)) {
    item.resources = [];
  }

  const newResource = {
    title: resourceBody.title,
    url: resourceBody.url,
    type: resourceBody.type || 'url',
    storageFileId: resourceBody.storageFileId || undefined,
    description: resourceBody.description || undefined,
  };

  item.resources.push(newResource);
  await item.save();

  return item.resources;
};

